export interface TextAssignmentDraft {
  /** Stable within one Maestro delegation; generated by validation when omitted by the model. */
  readonly assignmentId?: string;
  /** Internal stable durable child identity, assigned by Maestro after validation. */
  readonly executionTaskId?: TaskId;
  /** Assignment IDs that must complete before this assignment can start. */
  readonly dependsOn?: ReadonlyArray<string>;
  readonly definitionId: string;
  readonly objective: string;
  readonly relevantContext: string;
  readonly relevantContextRefs: ReadonlyArray<string>;
  readonly constraints: ReadonlyArray<string>;
  readonly expectedOutcome: string;
  readonly evidenceExpectations: ReadonlyArray<string>;
  /** Capabilities the selected executor must provide; omitted means supplied-context text analysis. */
  readonly requiredCapabilities?: ReadonlyArray<string>;
}

/** A group finding is required only when the assigned work explicitly asks for one. */
export function requiresGroupFinding(assignment: Pick<TextAssignmentDraft, 'objective' | 'expectedOutcome' | 'constraints'>): boolean {
  return [assignment.objective, assignment.expectedOutcome, ...assignment.constraints].some(value => {
    const text = value.toLowerCase();
    return /\b(?:publish|post|share|contribute|send)\b/.test(text)
      && /\b(?:group|shared)\b/.test(text) && /\bfinding\b/.test(text);
  });
}
export interface WorkerReport {
  readonly assignmentId: AssignmentId;
  readonly taskId: TaskId;
  readonly workerId: WorkerId;
  readonly mediobotId: MediobotDefinitionId;
  readonly providerId?: string;
  readonly modelId?: string;
  readonly startedAt?: number;
  readonly completedAt?: number;
  readonly status: 'completed' | 'failed' | 'cancelled' | 'model-unavailable' | 'blocked';
  readonly summary: string;
  /** Model claims over supplied context, never independently verified external evidence. */
  readonly evidence: ReadonlyArray<string>;
  readonly artifacts: ReadonlyArray<string>;
  readonly blockers: ReadonlyArray<string>;
  readonly unresolved: ReadonlyArray<string>;
  readonly groupMessages?: ReadonlyArray<{ readonly kind: 'finding' | 'request'; readonly content: string; readonly evidenceRefs?: ReadonlyArray<string> }>;
}
